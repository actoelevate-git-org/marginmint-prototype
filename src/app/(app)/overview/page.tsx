import { Download } from "lucide-react";
import type { Metadata } from "next";
import { InsightsList } from "@/components/dashboard/insights-list";
import { KpiGrid } from "@/components/dashboard/kpi-card";
import { MarketplaceTable } from "@/components/dashboard/marketplace-table";
import { ProfitWaterfall } from "@/components/dashboard/profit-waterfall";
import { RevenueProfitChart } from "@/components/dashboard/revenue-profit-chart";
import { buttonVariants } from "@/components/ui/button";
import { Card, CardContent, CardFooter, CardHeader } from "@/components/ui/card";
import { EmptyState } from "@/components/ui/empty-state";
import { PageHeader } from "@/components/ui/page-header";
import { InfoTooltip } from "@/components/ui/tooltip";
import { parseGlobalFilters, type SearchParams } from "@/lib/search-params";
import { getDashboardModel } from "@/services/dashboard";
import { getCurrentWorkspace } from "@/services/workspace";

export const metadata: Metadata = { title: "Overview" };

export default async function OverviewPage({ searchParams }: { searchParams: Promise<SearchParams> }) {
  const params = await searchParams;
  const workspace = getCurrentWorkspace();
  const filters = parseGlobalFilters(params, workspace.today);
  const model = getDashboardModel(filters);

  return (
    <div className="space-y-5">
      <PageHeader
        eyebrow={`Welcome back, ${model.ownerName}`}
        title="Business overview"
        description={
          <>
            {model.marketplaceLabel} · {model.rangeLabel}
            {model.comparisonLabel ? ` · compared ${model.comparisonLabel}` : " · no comparison (prior period predates demo history)"}
          </>
        }
        actions={
          <a href={model.exportHref} className={buttonVariants({ variant: "secondary" })} download>
            <Download aria-hidden="true" />
            Export P&amp;L (CSV)
          </a>
        }
      />

      <KpiGrid kpis={model.kpis} />

      <p className="text-xs text-muted">
        <span className="font-medium text-slate-600">Estimated figures.</span> {model.coverage.reason}
      </p>

      <div className="grid grid-cols-1 gap-4 xl:grid-cols-5">
        <Card className="xl:col-span-3">
          <CardHeader
            title="Revenue vs profit"
            description="All three series are in rupees on one axis."
            titleAddon={
              <InfoTooltip
                label="Revenue vs profit"
                content="Net sales, gross profit (after COGS) and net profit (after all recorded costs). Expenses are booked on the day they are recorded, so monthly bills appear as dips."
              />
            }
          />
          <RevenueProfitChart daily={model.trend.daily} weekly={model.trend.weekly} />
        </Card>
        <Card className="xl:col-span-2">
          <CardHeader
            title="Where the money goes"
            description="From net sales to net profit for the selected period."
            titleAddon={
              <InfoTooltip
                label="Profit breakdown"
                content="Each grey bar is a cost that reduces the running total. Refund & return losses = refunds + return shipping − cost of stock recovered. Other expenses are recorded operating costs such as packaging and software."
              />
            }
          />
          <CardContent className="pt-2">
            {"steps" in model.waterfall ? (
              <ProfitWaterfall steps={model.waterfall.steps} />
            ) : (
              <EmptyState title="Breakdown unavailable" description={model.waterfall.unavailable} />
            )}
          </CardContent>
        </Card>
      </div>

      <Card>
        <CardHeader title="Marketplace performance" description={`${model.rangeLabel} · all channels shown for comparison`} />
        <div className="mt-3">
          <MarketplaceTable rows={model.marketplaces} />
        </div>
        {model.sharedOverheadNote ? <CardFooter>{model.sharedOverheadNote}</CardFooter> : null}
      </Card>

      <Card>
        <CardHeader
          title="Needs your attention"
          description="Generated by deterministic rules from your records. Each item links to the underlying data."
          titleAddon={
            model.insights.length > 0 ? (
              <span className="num rounded-full bg-slate-100 px-1.5 text-2xs font-medium text-slate-600">{model.insights.length}</span>
            ) : null
          }
        />
        <div className="mt-2">
          <InsightsList insights={model.insights} />
        </div>
      </Card>
    </div>
  );
}
